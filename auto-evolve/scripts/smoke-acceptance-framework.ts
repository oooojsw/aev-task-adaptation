import path from "node:path"
import process from "node:process"
import { rm } from "node:fs/promises"
import { runCase } from "../orchestrator/case-runner"
import { runLongTask } from "../orchestrator/long-task/runner"
import { runBlankAgentSingleSessionCaseAcceptance } from "../orchestrator/acceptance-framework/run"
import { buildMinimalExperienceWorkspaceSeed, experienceWorkspacePathsFromRoot, restoreExperienceWorkspace } from "../orchestrator/experience-workspace"
import { autoEvolvePath, ensureDirectory, readJsonFile, writeJsonFile, writeTextFile } from "../orchestrator/fs"
import { loadConfig, type CaseSpec } from "../orchestrator/schema"

function stamp() {
  const now = new Date()
  return `${now.getFullYear()}${String(now.getMonth() + 1).padStart(2, "0")}${String(now.getDate()).padStart(2, "0")}-${String(now.getHours()).padStart(2, "0")}${String(now.getMinutes()).padStart(2, "0")}${String(now.getSeconds()).padStart(2, "0")}${String(now.getMilliseconds()).padStart(3, "0")}`
}

function relToAutoRoot(cwd: string, target: string) {
  return path.relative(autoEvolvePath(cwd), target).replace(/\\/g, "/")
}

async function seedWorkspace(root: string, entryFile: string, token: string) {
  const workspacePaths = experienceWorkspacePathsFromRoot(root, entryFile)
  const seed = buildMinimalExperienceWorkspaceSeed(workspacePaths)
  seed["core/expert_rules.md"] = [
    "<!-- auto-evolve-role: rule_module -->",
    "# Smoke Rules",
    "",
    `- When the task asks for the smoke token, return ${token}.`,
    "",
  ].join("\n")
  seed["core/output_contract.md"] = [
    "<!-- auto-evolve-role: output_contract -->",
    "# Output Contract",
    "",
    `- Final answer must include ${token}.`,
    "",
  ].join("\n")
  seed["core/execution_checklist.md"] = [
    "<!-- auto-evolve-role: execution_checklist -->",
    "# Execution Checklist",
    "",
    "- Read the task material first.",
    "- Read the tracked expert workspace entry and core rules.",
    `- Before finalizing, verify the output still includes ${token}.`,
    "",
  ].join("\n")
  seed["tools/README.md"] = [
    "# Tools",
    "",
    "- This smoke workspace intentionally uses no task-specific runtime tools.",
    "",
  ].join("\n")
  await restoreExperienceWorkspace(workspacePaths, seed)
  return workspacePaths
}

async function writeShortSmokeCase(cwd: string, caseID: string, token: string) {
  const caseDir = path.join(autoEvolvePath(cwd), "dataset", "cases", caseID)
  await ensureDirectory(path.join(caseDir, "material"))
  await ensureDirectory(path.join(caseDir, "expected"))
  const spec: CaseSpec = {
    id: caseID,
    instruction: "Read the attached material and return an answer that contains the expected smoke token.",
    materials: [{ path: "material/prompt.txt", label: "smoke prompt" }],
    expected: {
      path: "expected/output.txt",
      mode: "text_contains",
    },
    tags: ["system_smoke", "acceptance_framework"],
    notes: "Temporary smoke case generated by the acceptance framework smoke runner.",
  }
  await writeJsonFile(path.join(caseDir, "case.json"), spec)
  await writeTextFile(
    path.join(caseDir, "material", "prompt.txt"),
    [
      "Read this prompt and return the smoke token.",
      `Smoke token: ${token}`,
      "Your final answer may be a single line, but it must include the token.",
      "",
    ].join("\n"),
  )
  await writeTextFile(path.join(caseDir, "expected", "output.txt"), token)
  return { caseDir, spec }
}

async function writeDeploymentCase(caseRoot: string, token: string, expectedToken: string) {
  await ensureDirectory(path.join(caseRoot, "material"))
  await ensureDirectory(path.join(caseRoot, "expected"))
  const spec: CaseSpec = {
    id: path.basename(caseRoot),
    instruction: "Read the attached material and return the requested smoke token.",
    materials: [{ path: "material/prompt.txt", label: "deployment smoke prompt" }],
    expected: {
      path: "expected/output.txt",
      mode: "text_contains",
    },
    tags: ["system_smoke", "deployment_acceptance"],
  }
  await writeJsonFile(path.join(caseRoot, "case.json"), spec)
  await writeTextFile(
    path.join(caseRoot, "material", "prompt.txt"),
    [
      "This is a deployment-acceptance smoke case.",
      `Return a final answer that includes ${token}.`,
      "",
    ].join("\n"),
  )
  await writeTextFile(path.join(caseRoot, "expected", "output.txt"), expectedToken)
  return spec
}

async function writeLongTaskSmokeSpec(cwd: string, smokeRoot: string, token: string) {
  const taskRoot = path.join(smokeRoot, "long-task")
  const materialsDir = path.join(taskRoot, "materials")
  const outputsDir = path.join(taskRoot, "outputs")
  await ensureDirectory(materialsDir)
  await ensureDirectory(outputsDir)

  const materialPath = path.join(materialsDir, "goal.txt")
  const targetPath = path.join(outputsDir, "result.txt")
  const validatorPath = path.join(autoEvolvePath(cwd), "scripts", "validate-text-target-contains.ps1")
  const specPath = path.join(taskRoot, "spec.json")

  await writeTextFile(
    materialPath,
    [
      "This is a generic long-task acceptance smoke case.",
      `Write the exact token ${token} into the target file.`,
      "",
    ].join("\n"),
  )

  await writeJsonFile(specPath, {
    id: "long-task-acceptance-framework-smoke",
    title: "Long Task Acceptance Framework Smoke",
    goal: `Write the smoke token ${token} into the target file and satisfy all validators.`,
    taskFamily: "system_smoke",
    domainTags: ["system_smoke", "acceptance_framework", "long_task"],
    materials: [{ path: materialPath, label: "goal material" }],
    targetPaths: [{ path: targetPath, label: "smoke target" }],
    editablePaths: [targetPath],
    validators: [
      {
        id: "target-contains-token",
        type: "script",
        title: "Target Contains Smoke Token",
        path: validatorPath,
        runner: "powershell",
        inputMode: "json_file",
        args: [token],
        required: true,
        blocking: true,
      },
    ],
    reversePropagation: {
      acceptancePolicyID: "long-task-candidate-guard",
    },
    initialGraph: {
      planner_summary: "Single-unit smoke graph.",
      completion_validator_ids: ["target-contains-token"],
      units: [
        {
          id: "write-target-file",
          title: "Write Target File",
          goal: `Write ${token} into the target file.`,
          inputs: [materialPath],
          depends_on: [],
          expected_artifacts: [targetPath],
          claim: `The target file exists and contains ${token}.`,
          check_plan: "Use the validator to confirm the target file contains the smoke token before claiming success.",
          validator_ids: ["target-contains-token"],
          retry_budget: 2,
        },
      ],
    },
    budgets: {
      maxAttemptsPerUnit: 2,
      maxTotalUnitAttempts: 3,
      maxGraphReplans: 0,
      maxValidatorCalls: 4,
      maxNoProgressCycles: 2,
      maxUnitsPerGraph: 2,
    },
    notes: "Generic acceptance framework smoke long-task.",
  })

  return { specPath, targetPath }
}

async function main() {
  const cwd = process.argv[2] ? path.resolve(process.argv[2]) : process.cwd()
  const config = await loadConfig(cwd)
  const token = `ACCEPTANCE-FRAMEWORK-SMOKE-${stamp()}`
  const smokeRoot = path.join(autoEvolvePath(cwd), "runtime-state", "acceptance-framework", "smoke", stamp())
  const shortCaseID = `case-smoke-${stamp()}`
  const summaryPath = path.join(smokeRoot, "summary.json")

  await ensureDirectory(smokeRoot)

  const shortWorkspaceRoot = path.join(smokeRoot, "short-workspace")
  await seedWorkspace(shortWorkspaceRoot, config.experienceEntryFile, token)

  const shortCase = await writeShortSmokeCase(cwd, shortCaseID, token)
  const shortRunsRoot = path.join(smokeRoot, "short-runs")

  try {
    const shortResult = await runCase(cwd, shortCaseID, {
      methodID: "sequential-refine",
      mode: "eval",
      split: "all",
      runtimePaths: {
        knowledgeDir: relToAutoRoot(cwd, shortWorkspaceRoot),
        runsDir: relToAutoRoot(cwd, shortRunsRoot),
      },
    })

    const deploymentWorkspaceRoot = path.join(smokeRoot, "deployment-workspace")
    await seedWorkspace(deploymentWorkspaceRoot, config.experienceEntryFile, token)

    const deploymentPositiveRoot = path.join(smokeRoot, "deployment-positive")
    const deploymentNegativeRoot = path.join(smokeRoot, "deployment-negative")
    const positiveSpec = await writeDeploymentCase(deploymentPositiveRoot, token, token)
    const negativeSpec = await writeDeploymentCase(deploymentNegativeRoot, token, `${token}-NEGATIVE`)

    const positiveDeployment = await runBlankAgentSingleSessionCaseAcceptance({
      cwd,
      sourceRunID: `deployment-positive-${stamp()}`,
      targetKind: "canonical_experience",
      targetID: "deployment-positive-smoke",
      workspaceRoot: deploymentWorkspaceRoot,
      caseDir: deploymentPositiveRoot,
      caseSpec: positiveSpec,
      harnessRoot: path.join(smokeRoot, "deployment-harness"),
      policyID: "blank-agent-single-session-gate",
      executionProfile: "full",
    })

    const negativeDeployment = await runBlankAgentSingleSessionCaseAcceptance({
      cwd,
      sourceRunID: `deployment-negative-${stamp()}`,
      targetKind: "canonical_experience",
      targetID: "deployment-negative-smoke",
      workspaceRoot: deploymentWorkspaceRoot,
      caseDir: deploymentNegativeRoot,
      caseSpec: negativeSpec,
      harnessRoot: path.join(smokeRoot, "deployment-harness"),
      policyID: "blank-agent-single-session-gate",
      executionProfile: "full",
    })

    const longTask = await writeLongTaskSmokeSpec(cwd, smokeRoot, token)
    const longResult = await runLongTask({
      cwd,
      specPath: longTask.specPath,
    })

    const localAcceptanceMirrorPath = path.join(
      longResult.runDir,
      "units",
      "write-target-file",
      "attempt-01",
      "acceptance",
      "local_guard.json",
    )
    const candidateAcceptanceMirrorPath = path.join(longResult.runDir, "acceptance", "candidate_guard.json")

    const summary = {
      smokeRoot,
      short: {
        caseID: shortCaseID,
        runDir: shortResult.runDir,
        passed: shortResult.evaluation.passed,
        summary: shortResult.evaluation.summary,
      },
      deployment: {
        positive: {
          runDir: positiveDeployment.runDir,
          passed: positiveDeployment.evaluation.passed,
          acceptanceRecordPath: positiveDeployment.acceptanceRecordPath,
        },
        negative: {
          runDir: negativeDeployment.runDir,
          passed: negativeDeployment.evaluation.passed,
          acceptanceRecordPath: negativeDeployment.acceptanceRecordPath,
        },
      },
      longTask: {
        runDir: longResult.runDir,
        status: longResult.status,
        summaryPath: longResult.summaryPath,
        localAcceptanceMirrorPath,
        candidateAcceptanceMirrorPath,
      },
    }

    await writeJsonFile(summaryPath, summary)
    await writeTextFile(
      path.join(smokeRoot, "summary.md"),
      [
        "# Acceptance Framework Smoke",
        "",
        `- short case passed: ${summary.short.passed}`,
        `- deployment positive passed: ${summary.deployment.positive.passed}`,
        `- deployment negative passed: ${summary.deployment.negative.passed}`,
        `- long-task status: ${summary.longTask.status}`,
        `- local acceptance mirror: ${summary.longTask.localAcceptanceMirrorPath}`,
        `- candidate acceptance mirror: ${summary.longTask.candidateAcceptanceMirrorPath}`,
        "",
      ].join("\n"),
    )

    if (!summary.short.passed) {
      throw new Error(`Short smoke case failed: ${summary.short.summary}`)
    }
    if (!summary.deployment.positive.passed) {
      throw new Error("Deployment positive smoke case failed.")
    }
    if (summary.deployment.negative.passed) {
      throw new Error("Deployment negative smoke case unexpectedly passed.")
    }
    if (summary.longTask.status !== "verified_success") {
      throw new Error(`Long-task smoke failed with status ${summary.longTask.status}.`)
    }

    const localAcceptance = await readJsonFile<Record<string, unknown>>(localAcceptanceMirrorPath)
    const candidateAcceptance = await readJsonFile<Record<string, unknown>>(candidateAcceptanceMirrorPath)
    if (localAcceptance.status !== "observed" && localAcceptance.status !== "passed") {
      throw new Error(`Local long-task acceptance record was not passed: ${JSON.stringify(localAcceptance)}`)
    }
    if (candidateAcceptance.status !== "passed") {
      throw new Error(`Candidate long-task acceptance record was not passed: ${JSON.stringify(candidateAcceptance)}`)
    }

    console.log(JSON.stringify(summary, null, 2))
  } finally {
    await rm(shortCase.caseDir, { recursive: true, force: true })
  }
}

await main()
